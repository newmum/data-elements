import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const signature=createHash('sha256').update(JSON.stringify({dependencies:pkg.dependencies,devDependencies:pkg.devDependencies})).digest('hex');
const marker='.wanxiang-dependencies.json';
let prepared=false;try{prepared=JSON.parse(fs.readFileSync(marker,'utf8')).signature===signature;}catch{/* first startup */}
for(const [name,version] of Object.entries({...pkg.dependencies,...pkg.devDependencies})){
  try{if(JSON.parse(fs.readFileSync(path.join('node_modules',name,'package.json'),'utf8')).version!==version)prepared=false;}catch{prepared=false;}
}
if(!prepared){
  let locked=false;try{const root=JSON.parse(fs.readFileSync('package-lock.json','utf8')).packages?.[''];const same=(a,b)=>Object.keys(a??{}).length===Object.keys(b??{}).length&&Object.entries(a??{}).every(([k,v])=>b?.[k]===v);locked=same(root?.dependencies,pkg.dependencies)&&same(root?.devDependencies,pkg.devDependencies);}catch{/* a lockfile will be generated by npm */}
  console.log('Checking updated Wanxiang dependencies...');
  const result=spawnSync(process.platform==='win32'?'npm.cmd':'npm',[locked?'ci':'install'],{stdio:'inherit',shell:process.platform==='win32'});
  if(result.error)console.error(result.error.message);
  if(result.status!==0)process.exit(result.status??1);
  fs.writeFileSync(marker,JSON.stringify({signature},null,2));
}
